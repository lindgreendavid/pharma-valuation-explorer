/* Port of src/pharma_valuation/model.py. Same formulas, same units (millions of reporting currency;
   percentages as fractions). tests/engine.test.mjs checks it against vectors generated by the Python model. */
(function (root) {
  "use strict";

  function makeDataset(payload) {
    const facts = new Map();
    for (const f of payload.facts) facts.set(`${f.company}|${f.fiscal_year}|${f.field}`, f);
    const fx = new Map();
    for (const r of payload.fx) fx.set(`${r.currency}|${r.kind}|${r.period.slice(0, 4)}`, Number(r.rate));
    return {
      payload,
      has: (company, year, name) => facts.has(`${company}|${year}|${name}`),
      get(company, year, name, fallback) {
        const fact = facts.get(`${company}|${year}|${name}`);
        if (!fact) {
          if (fallback === undefined) throw new Error(`missing ${company} ${year} ${name}`);
          return fallback;
        }
        return Number(fact.value);
      },
      fact: (company, year, name) => facts.get(`${company}|${year}|${name}`),
      currency: (company) => payload.companies[company].currency,
      eurRate(currency, kind, year) {
        return currency === "EUR" ? 1 : fx.get(`${currency}|${kind}|${year}`);
      },
    };
  }

  function grossDebt(d, c, y) {
    return d.get(c, y, "debt_current") + d.get(c, y, "debt_noncurrent") + d.get(c, y, "lease_current", 0) + d.get(c, y, "lease_noncurrent", 0);
  }

  function debtLikeOther(d, c, y) {
    return d.get(c, y, "contingent_consideration_current", 0) + d.get(c, y, "contingent_consideration_noncurrent", 0);
  }

  function freeCashFlow(d, c, y) {
    const capex = d.get(c, y, "capex_ppe") + d.get(c, y, "capex_intangibles");
    const adjustment = -d.get(c, y, "interest_paid_outside_cfo", 0) + d.get(c, y, "interest_received_outside_cfo", 0);
    return d.get(c, y, "cfo") - capex + adjustment;
  }

  function metrics(d, c, y) {
    const revenue = d.get(c, y, "revenue");
    const operating = d.get(c, y, "operating_income");
    const m = {
      revenue,
      operating_income: operating,
      operating_margin: operating / revenue,
      r_and_d_intensity: d.get(c, y, "r_and_d") / revenue,
      net_income: d.get(c, y, "net_income"),
      net_margin: d.get(c, y, "net_income") / revenue,
      effective_tax_rate: d.get(c, y, "income_tax") / d.get(c, y, "pretax_income"),
      operating_cash_flow: d.get(c, y, "cfo"),
      capex: d.get(c, y, "capex_ppe") + d.get(c, y, "capex_intangibles"),
      free_cash_flow: freeCashFlow(d, c, y),
    };
    m.fcf_margin = m.free_cash_flow / revenue;
    m.fcf_to_net_income = m.free_cash_flow / m.net_income;
    m.gross_debt = grossDebt(d, c, y);
    m.cash_and_investments = d.get(c, y, "cash") + d.get(c, y, "short_term_investments", 0);
    m.net_debt = m.gross_debt + debtLikeOther(d, c, y) - m.cash_and_investments;
    m.net_debt_to_operating_income = m.net_debt / operating;
    if (d.has(c, y - 1, "revenue")) m.revenue_growth = revenue / d.get(c, y - 1, "revenue") - 1;
    return m;
  }

  function toEur(d, c, y, value, kind) {
    const rateKind = kind === "flow" ? "annual_average" : "year_end";
    return value / d.eurRate(d.currency(c), rateKind, y);
  }

  const DEFAULT_BRIDGE = {
    includeEquityMethod: true,
    includeOtherFinancial: true,
    includePension: true,
    nciMethod: "book",
    nciEarningsMultiple: 15,
  };

  function equityBridge(d, c, y, enterpriseValue, options) {
    const o = Object.assign({}, DEFAULT_BRIDGE, options || {});
    const items = [];
    const add = (label, amount, source) => items.push({ label, amount, source });
    add("Enterprise value", enterpriseValue, "model");
    add("Less: gross borrowings and lease liabilities", -grossDebt(d, c, y), "balance sheet");
    const other = debtLikeOther(d, c, y);
    if (other) add("Less: contingent consideration liabilities (debt-like)", -other, "balance sheet");
    add("Plus: cash and cash equivalents", d.get(c, y, "cash"), "balance sheet");
    const st = d.get(c, y, "short_term_investments", 0);
    if (st) add("Plus: marketable securities and short-term investments", st, "balance sheet");
    if (o.includeEquityMethod) add("Plus: investments in associates and joint ventures (book)", d.get(c, y, "equity_method_investments", 0), "balance sheet");
    if (o.includeOtherFinancial) add("Plus: other non-current financial assets (book)", d.get(c, y, "other_financial_assets", 0), "balance sheet");
    if (o.includePension) add("Less: recognised post-employment liabilities", -d.get(c, y, "pension_liability", 0), "balance sheet or note");
    if (o.nciMethod === "earnings_multiple") {
      const nci = Math.max(d.get(c, y, "nci_profit", 0), 0) * o.nciEarningsMultiple;
      add(`Less: non-controlling interests (${o.nciEarningsMultiple}x their profit)`, -nci, "income statement, assumption");
    } else {
      add("Less: non-controlling interests (book value)", -d.get(c, y, "nci_book", 0), "balance sheet");
    }
    return { items, equity_value: items.reduce((s, i) => s + i.amount, 0) };
  }

  function project(inputs) {
    if (inputs.growth.length !== inputs.operating_margin.length) throw new Error("growth and operating_margin must have the same length");
    const rows = [];
    let revenue = inputs.base_revenue;
    let nwc = inputs.base_nwc;
    inputs.growth.forEach((growth, index) => {
      revenue *= 1 + growth;
      const ebit = revenue * inputs.operating_margin[index];
      const nopat = ebit * (1 - inputs.tax_rate);
      const da = revenue * inputs.da_pct_revenue;
      const capex = revenue * inputs.capex_pct_revenue;
      const newNwc = revenue * inputs.nwc_pct_revenue;
      const deltaNwc = newNwc - nwc;
      nwc = newNwc;
      rows.push({ year: index + 1, revenue, ebit, nopat, da, capex, delta_nwc: deltaNwc, fcff: nopat + da - capex - deltaNwc });
    });
    return rows;
  }

  function terminalFcf(inputs, last) {
    const g = inputs.terminal_growth;
    const nopat = last.nopat * (1 + g);
    const deltaNwc = inputs.nwc_pct_revenue * last.revenue * g;
    const normalise = inputs.normalise_terminal !== false;
    const netCapex = normalise ? 0 : (last.capex - last.da) * (1 + g);
    return nopat - netCapex - deltaNwc;
  }

  function enterpriseValue(inputs, rows) {
    if (inputs.wacc <= inputs.terminal_growth) throw new Error("WACC must exceed terminal growth");
    const r = rows || project(inputs);
    const shift = inputs.mid_year ? 0.5 : 0;
    const pvExplicit = r.reduce((s, row) => s + row.fcff / Math.pow(1 + inputs.wacc, row.year - shift), 0);
    const last = r[r.length - 1];
    const terminalValue = terminalFcf(inputs, last) / (inputs.wacc - inputs.terminal_growth);
    const pvTerminal = terminalValue / Math.pow(1 + inputs.wacc, last.year - shift);
    return {
      pv_explicit: pvExplicit,
      terminal_value: terminalValue,
      pv_terminal: pvTerminal,
      enterprise_value: pvExplicit + pvTerminal,
      terminal_share_of_value: pvTerminal / (pvExplicit + pvTerminal),
    };
  }

  function waccBuildUp(riskFree, beta, erp, preTaxCostOfDebt, taxRate, debtWeight) {
    const costOfEquity = riskFree + beta * erp;
    const costOfDebt = preTaxCostOfDebt * (1 - taxRate);
    return { cost_of_equity: costOfEquity, after_tax_cost_of_debt: costOfDebt, wacc: (1 - debtWeight) * costOfEquity + debtWeight * costOfDebt };
  }

  function sensitivityGrid(inputs, waccs, terminalGrowths) {
    const rows = project(inputs);
    return waccs.map((wacc) =>
      terminalGrowths.map((g) => enterpriseValue(Object.assign({}, inputs, { wacc, terminal_growth: g }), rows).enterprise_value),
    );
  }

  const api = { makeDataset, grossDebt, debtLikeOther, freeCashFlow, metrics, toEur, equityBridge, project, terminalFcf, enterpriseValue, waccBuildUp, sensitivityGrid, DEFAULT_BRIDGE };
  if (typeof module !== "undefined" && module.exports) module.exports = api;
  root.PharmaEngine = api;
})(typeof globalThis !== "undefined" ? globalThis : this);
